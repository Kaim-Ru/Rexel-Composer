import { execFileSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const cli = join(root, "packages", "cli", "dist", "main.js");
const references = join(root, "skills", "rexel-composer", "references");

const CATEGORY_TITLES = {
  io: "Input / Output",
  generate: "Generate",
  color: "Color",
  filter: "Filter",
  transform: "Transform",
  composite: "Composite",
  value: "Value",
  plugin: "Plugins",
};

const LINKABLE = { number: "number", integer: "number", color: "color", vector: "vector" };

function rexel(...args) {
  return execFileSync(process.execPath, [cli, ...args], { encoding: "utf8" });
}

function describeParam(name, spec) {
  const parts = [spec.kind];
  if (spec.kind === "enum") parts.push(spec.options.map((option) => `\`${option}\``).join(" / "));
  if (spec.kind === "asset")
    parts.push(`${spec.assetKind} asset id${spec.optional ? ", optional" : ""}`);
  if (spec.min !== undefined || spec.max !== undefined)
    parts.push(`${spec.min ?? "-∞"}..${spec.max ?? "∞"}`);
  if (spec.default !== undefined) parts.push(`default \`${JSON.stringify(spec.default)}\``);
  if (LINKABLE[spec.kind] !== undefined) parts.push(`linkable as ${LINKABLE[spec.kind]}`);
  return `\`${name}\` (${parts.join(", ")})`;
}

function ports(record) {
  const entries = Object.entries(record);
  return entries.length === 0
    ? "none"
    : entries.map(([name, type]) => `\`${name}\`: ${type}`).join(", ");
}

const nodes = JSON.parse(rexel("nodes", "--json"));
const lines = [
  "# Node reference",
  "",
  "Generated by `pnpm skill` from `rexel nodes --json`. Do not edit by hand.",
  "",
];
for (const [category, title] of Object.entries(CATEGORY_TITLES)) {
  const members = nodes.filter((node) => node.category === category);
  if (members.length === 0) continue;
  lines.push(`## ${title}`, "");
  for (const node of members) {
    const params = Object.entries(node.params);
    lines.push(
      `### \`${node.type}\` — ${node.title}`,
      "",
      `- Inputs: ${ports(node.inputs)}`,
      `- Outputs: ${ports(node.outputs)}`,
      `- Params: ${params.length === 0 ? "none" : params.map(([name, spec]) => describeParam(name, spec)).join("; ")}`,
      "",
    );
  }
}

mkdirSync(references, { recursive: true });
writeFileSync(join(references, "nodes.md"), lines.join("\n"));
writeFileSync(join(references, "project.schema.json"), rexel("schema"));
console.log(`Wrote ${nodes.length} nodes and the project schema to ${references}`);
